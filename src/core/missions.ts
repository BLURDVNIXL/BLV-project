export function getMissionForDestiny(destinyId: string): DestinyMission {
  return DESTINY_MISSIONS[destinyId] || DESTINY_MISSIONS.debrouillard_abobo;
}

export function isMissionStepSatisfied(
  state: PlayerState,
  step: MissionStep,
  currentDistrictId?: string
): boolean {
  switch (step.conditionKind) {
    case 'visit_district':
      return currentDistrictId === step.targetDistrictId;
    case 'work_shifts':
      return state.activeMission.workCount >= step.conditionTarget;
    case 'eat_meals':
      return state.activeMission.eatCount >= step.conditionTarget;
    case 'bank_balance':
      return state.bankCash >= step.conditionTarget;
    case 'school_badge':
      return state.activeBadges.length >= step.conditionTarget;
    case 'star_threshold':
      return state.star >= step.conditionTarget;
    case 'crib_upgrade': {
      const count = Object.values(state.cribUpgrades).filter(Boolean).length;
      return count >= step.conditionTarget;
    }
    case 'clear_police':
      return state.policeWanted <= step.conditionTarget;
    case 'clean_days':
      return state.redemptionTrophyUnlocked || state.cleanDaysStreak >= step.conditionTarget || state.star >= 75;
    case 'academy_level':
      return state.yannisAcademyLevel >= step.conditionTarget;
    default:
      return false;
  }
}
